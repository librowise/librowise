#!/usr/bin/env python3
"""Generate man pages from the CLI's argparse definitions.

    python packaging/gen-manpages.py OUTDIR [--version 1.0.0]

Writes OUTDIR/man1/librowise.1 (every command) and OUTDIR/man8/librowise-instance.8 (instance
administration). The parser is captured by intercepting ``parse_args`` while running ``main``,
so the CLI module needs no changes and the pages always match ``--help``.
"""

from __future__ import annotations

import argparse
import datetime as dt
import importlib
import os
import re
import sys
from pathlib import Path

PY_MODULE = "shelfwise"  # renamed together with the project
PROG = "librowise"
TITLE = "Librowise"


class _Captured(Exception):
    pass


def capture_parser() -> argparse.ArgumentParser:
    cli = importlib.import_module(f"{PY_MODULE}.__main__")
    original = argparse.ArgumentParser.parse_args

    def intercept(self, *a, **k):
        raise _Captured(self)

    argparse.ArgumentParser.parse_args = intercept
    try:
        cli.main([])
    except _Captured as exc:
        return exc.args[0]
    finally:
        argparse.ArgumentParser.parse_args = original
    raise RuntimeError("main() did not call parse_args")


def subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            return [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()
                    if not name.startswith("_")]
    return []


def esc(text: str) -> str:
    text = text.replace("\\", "\\e").replace("-", "\\-")
    return "\n".join(("\\&" + ln) if ln.startswith((".", "'")) else ln for ln in text.splitlines())


def rename(text: str, root_prog: str) -> str:
    return re.sub(rf"(?<![\w-]){re.escape(root_prog)}(?![\w-])", PROG, text)


def options_section(parser: argparse.ArgumentParser, root_prog: str) -> list[str]:
    out = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)) or action.help == argparse.SUPPRESS:
            continue
        if action.option_strings:
            metavar = ""
            if action.nargs != 0:
                metavar = " " + (action.metavar or (action.dest.upper() if not action.choices
                                                    else "{" + ",".join(map(str, action.choices)) + "}"))
            label = ", ".join(f"\\fB{esc(o)}\\fR" + (f"\\fI{esc(metavar)}\\fR" if metavar else "")
                              for o in action.option_strings)
        else:
            label = f"\\fI{esc(action.metavar or action.dest)}\\fR"
        out += [".TP", label, esc(rename(action.help or "", root_prog)) or "."]
    return out


def usage(parser: argparse.ArgumentParser, root_prog: str) -> str:
    text = parser.format_usage().strip()
    text = re.sub(r"^usage:\s*", "", text)
    return rename(re.sub(r"\s+", " ", text), root_prog)


def page(name: str, section: int, summary: str, body: list[str], version: str) -> str:
    date = dt.datetime.fromtimestamp(int(os.environ.get("SOURCE_DATE_EPOCH", "0")) or dt.datetime.now().timestamp(),
                                     dt.UTC).strftime("%Y-%m-%d")
    head = [
        f'.\\" Generated by packaging/gen-manpages.py from the {PROG} argparse definitions. Do not edit.',
        f'.TH "{name.upper()}" "{section}" "{date}" "{TITLE} {version}" "{TITLE} Manual"',
        ".SH NAME",
        f"{esc(name)} \\- {esc(summary)}",
    ]
    return "\n".join(head + body) + "\n"


def command_block(name: str, help_text: str, parser: argparse.ArgumentParser, root_prog: str, level: str) -> list[str]:
    lines = [f".{level} {esc(name)}", esc(rename(help_text, root_prog)) or ".", ".PP", ".nf",
             f"\\fB{esc(usage(parser, root_prog))}\\fR", ".fi"]
    if parser.description and parser.description != help_text:
        lines += [".PP", esc(rename(parser.description, root_prog))]
    lines += options_section(parser, root_prog)
    return lines


def build(version: str) -> dict[str, str]:
    root = capture_parser()
    root_prog = root.prog
    cmds = subcommands(root)
    main_body = [".SH SYNOPSIS", f"\\fB{PROG}\\fR \\fICOMMAND\\fR [\\fIOPTIONS\\fR]", ".SH DESCRIPTION",
                 f"{TITLE} is an integrated library system (catalogue, circulation, OPAC, serials, SIP2). "
                 f"The \\fB{PROG}\\fR command manages a database and its processes. Run it inside an "
                 f"instance's environment with \\fB{PROG} instance shell\\fR \\fINAME\\fR \\fB\\-\\-\\fR "
                 f"\\fICOMMAND\\fR, which loads /etc/{PROG}/\\fINAME\\fR.env.",
                 ".SH COMMANDS"]
    instance_parser = None
    for name, help_text, sub in cmds:
        if name == "instance":
            instance_parser = sub
            main_body += [f".SS {name}", esc(help_text), ".PP",
                          f"See \\fB{PROG}\\-instance\\fR(8)."]
            continue
        main_body += command_block(name, help_text, sub, root_prog, "SS")
    main_body += [".SH ENVIRONMENT",
                  f"Settings are read from environment variables prefixed with \\fB{esc(PY_MODULE.upper())}_\\fR "
                  "(see docs/DEPLOYMENT.md), normally from an instance env file.",
                  ".SH SEE ALSO", f"\\fB{PROG}\\-instance\\fR(8)"]
    pages = {f"man1/{PROG}.1": page(PROG, 1, "manage a Librowise library system", main_body, version)}
    if instance_parser is not None:
        body = [".SH SYNOPSIS", f"\\fB{PROG} instance\\fR \\fIACTION\\fR [\\fIOPTIONS\\fR]", ".SH DESCRIPTION",
                esc(rename(instance_parser.description or "", root_prog)),
                ".PP",
                f"Each instance is one library with its own database, /etc/{PROG}/\\fINAME\\fR.env, "
                f"/var/lib/{PROG}/\\fINAME\\fR, /var/log/{PROG}/\\fINAME\\fR, "
                f"/var/backups/{PROG}/\\fINAME\\fR and systemd units "
                f"{PROG}\\-web@\\fINAME\\fR, {PROG}\\-worker@\\fINAME\\fR and {PROG}\\-sip2@\\fINAME\\fR.",
                ".SH ACTIONS"]
        for name, help_text, sub in subcommands(instance_parser):
            body += command_block(name, help_text, sub, root_prog, "SS")
        body += [".SH FILES", ".TP", f"/etc/{PROG}/instances.json", "Instance registry (names, ports, domains).",
                 ".TP", f"/etc/{PROG}/\\fINAME\\fR.env", "Settings and secrets of an instance (root:librowise 0640).",
                 ".SH SEE ALSO", f"\\fB{PROG}\\fR(1), \\fBsystemctl\\fR(1), \\fBcaddy\\fR(1)"]
        pages[f"man8/{PROG}-instance.8"] = page(f"{PROG}-instance", 8, "create and manage Librowise instances",
                                                body, version)
    return pages


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("outdir")
    ap.add_argument("--version", default="")
    args = ap.parse_args(argv)
    version = args.version or importlib.import_module(PY_MODULE).__version__
    for rel, text in build(version).items():
        path = Path(args.outdir) / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
